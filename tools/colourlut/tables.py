"""Write core/src/color/colourlut-tables.ts from the approved colour LUTs (.npy).

The tables are made by the colour engine prototype (tools/colour_engine/engine.py `build_lut`, a work
directory of the project that is not in git; its notes are scratch/colour-engine/NOTES-v2.md): one
33 x 33 x 33 table of Q4 deltas (dY, dCb, dCr) per film, int16, C order [Y node][Cb node][Cr node][c].
The approved v2 tables:

    scratch/colour-engine/lut-cinestill-v2.npy     -> CineStill 800T
    scratch/colour-engine/lut-kodachrome-v2.npy    -> Kodachrome 64

and the "full look" tables of tools/colourlut/make_lut.py (camera today -> the film's authored cube):

    scratch/colour-engine/lut-classic-neg-full.npy     -> Classic Neg
    scratch/colour-engine/lut-classic-chrome-full.npy  -> Classic Chrome
    scratch/colour-engine/lut-blockbuster-full.npy     -> Blockbuster

    python tools/colourlut/tables.py [DIR]         DIR: the folder of the .npy files (default: GRMOD_COLOUR_ENGINE_DIR,
                                                   else scratch/colour-engine of this checkout or of the main checkout)

The module embeds the little-endian int16 data as base64 (215,622 bytes each) with the SHA-256 of the
.npy files they come from, so the origin of the data is recorded in git.
"""
import base64
import hashlib
import os
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
OUT = ROOT / 'core' / 'src' / 'color' / 'colourlut-tables.ts'
FILMS = [('CineStill 800T', 'lut-cinestill-v2.npy'), ('Kodachrome 64', 'lut-kodachrome-v2.npy'),
         ('Classic Neg', 'lut-classic-neg-full.npy'), ('Classic Chrome', 'lut-classic-chrome-full.npy'), ('Blockbuster', 'lut-blockbuster-full.npy')]


def find_dir():
    if len(sys.argv) > 1:
        return Path(sys.argv[1])
    cands = [os.environ.get('GRMOD_COLOUR_ENGINE_DIR'), ROOT / 'scratch' / 'colour-engine', *(p / 'scratch' / 'colour-engine' for p in ROOT.parents)]
    for c in cands:
        if c and (Path(c) / FILMS[0][1]).exists():
            return Path(c)
    sys.exit('the .npy files were not found; pass their folder')


def main():
    d = find_dir()
    rows = []
    for name, file in FILMS:
        raw = (d / file).read_bytes()
        a = np.load(d / file)
        if a.dtype != np.int16 or a.shape != (33, 33, 33, 3):
            sys.exit(f'{file}: expected int16 (33,33,33,3), got {a.dtype} {a.shape}')
        data = np.ascontiguousarray(a.astype('<i2')).tobytes()
        assert len(data) == 215622
        rows.append((name, file, hashlib.sha256(raw).hexdigest(), base64.b64encode(data).decode()))
    body = ''.join(
        f"  {{ film: '{n}', source: '{f}', sourceSha256: '{h}', data: b('{b}') }},\n" for n, f, h, b in rows)
    OUT.write_text(
        '// SPDX-License-Identifier: GPL-2.0-only\n'
        '// GENERATED by tools/colourlut/tables.py from the approved colour LUTs of the colour engine prototype\n'
        '// (tools/colour_engine/engine.py build_lut; scratch/colour-engine/lut-*-v2.npy) -- do not edit.\n'
        '// Each table: 33 x 33 x 33 x 3 little-endian int16, [Y node][Cb node][Cr node][dY dCb dCr], Q4 deltas\n'
        '// (sixteenths of a level), 215,622 bytes. `sourceSha256` is the SHA-256 of the .npy file.\n\n'
        "const b = (s: string) => Uint8Array.from(atob(s), c => c.charCodeAt(0));\n\n"
        'export interface ColourLutTable { film: string; source: string; sourceSha256: string; data: Uint8Array }\n'
        'export const COLOUR_LUT_TABLES: readonly ColourLutTable[] = [\n' + body + '];\n', encoding='utf-8', newline='\n')
    print(f'{OUT}: {OUT.stat().st_size} bytes')


if __name__ == '__main__':
    main()
