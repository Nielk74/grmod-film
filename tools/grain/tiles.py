"""Generate the grain tiles and brightness tables of grain v2 (tools/grain/grain.c) and write
core/src/color/grain-tables.ts.

Film grain is dye clouds: crisp, of several sizes, formed largely independently in each colour layer,
strongest in the shadows and lower midtones and fading towards the highlights. The tiles are cut from
the Boolean film grain model (Newson, Faraj, Galerne, Delon, "Realistic Film Grain Rendering", IPOL
2017) as tools/jpeg_experiments/grain_v3.py renders it: per dye layer, discs with log-normal radii at a
Poisson intensity that makes their coverage the layer's grey (here a flat mid grey), 4x supersampled,
box-averaged to pixels and blurred (sigma 0.5 px); the layers share 65 % of their grain, each layer's
own part softened into dye clouds (sigma 0.8 px). The camera lays a tile over the picture in blocks at
random offsets, as AV1's film grain synthesis does (grain.c).

Per grain size (small: disc radius 0.55 px of a 6000-wide picture; large: 1.3 px):
  - luma tile, 128 x 128 signed bytes, standard deviation 32;
  - colour tile, 128 rows of 64 (Cb, Cr) pairs, the same scale (4:2:2: one pair per two pixels);
  - brightness table, 256 bytes, the relative strength by Y (128 = as at mid grey): the reference's
    grain RMS by brightness, measured over real GR III photographs (grain_v3.fit_table, 31 Oct 2026),
    held at 0 at black and white.

    python tools/grain/tiles.py      (needs numpy and scipy)
"""
import base64
import hashlib
import sys
from pathlib import Path

import numpy as np
from scipy import ndimage

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(ROOT / 'tools' / 'jpeg_experiments'))
import grain_v3 as g  # noqa: E402

OUT = ROOT / 'core' / 'src' / 'color' / 'grain-tables.ts'
N = 128
RADIUS = (0.55, 1.3)
SEEDS = (7, 8)
# Relative luma grain RMS of the reference by Y (bin centres), measured on real photographs.
MEASURED = (
    {8: 0.574, 24: 0.894, 40: 1.28, 56: 1.435, 72: 1.213, 88: 1.101, 104: 1.035, 120: 1.01, 136: 0.99,
     152: 0.949, 168: 0.921, 184: 0.864, 200: 0.781, 216: 0.692, 232: 0.616, 248: 0.443},
    {8: 0.677, 24: 1.056, 40: 1.374, 56: 1.481, 72: 1.267, 88: 1.15, 104: 1.063, 120: 1.022, 136: 0.978,
     152: 0.932, 168: 0.903, 184: 0.822, 200: 0.745, 216: 0.652, 232: 0.598, 248: 0.506},
)


def tile(r, seed):
    rng = np.random.default_rng(seed)
    flat = np.full((N + 32, N + 32), 0.5)
    cov = np.stack([g.boolean_layer(flat, r, 0.4, rng) for _ in range(3)], -1)[16:-16, 16:-16]
    res = g.mix_layers(cov - cov.mean((0, 1)), 0.65)
    y, cb, cr = g.to_ycc(-res)          # darkness -> brightness, in YCbCr units
    s = y.std()
    cb2 = cb.reshape(N, N // 2, 2).mean(-1) / s
    cr2 = cr.reshape(N, N // 2, 2).mean(-1) / s
    q = lambda a: np.clip(np.round(a * 32), -127, 127).astype(np.int8)  # noqa: E731
    luma = q(y / s)
    colour = np.stack([q(cb2), q(cr2)], -1).reshape(N, N)   # rows of Cb, Cr pairs
    return luma, colour


def table(measured):
    xs = np.array([0] + sorted(measured) + [255], dtype=float)
    ys = np.array([0.0] + [measured[k] for k in sorted(measured)] + [0.0])
    t = ndimage.gaussian_filter1d(np.interp(np.arange(256), xs, ys), 4)
    t = t / t[128] * 128
    t[0] = t[255] = 0
    return np.clip(np.round(t), 0, 255).astype(np.uint8)


def b64(a):
    return base64.b64encode(a.tobytes()).decode()


def main():
    parts = []
    stats = []
    for k, (r, seed) in enumerate(zip(RADIUS, SEEDS)):
        luma, colour = tile(r, seed)
        tone = table(MEASURED[k])
        parts.append((luma, colour, tone))
        stats.append(f'{["small", "large"][k]}: luma std {luma.std():.1f}, colour std {colour.std():.1f}, '
                     f'tone peak {tone.max()} at Y {int(tone.argmax())}')
    src = (HERE / 'tiles.py').read_bytes().replace(b'\r\n', b'\n')
    lines = [
        '// SPDX-License-Identifier: GPL-2.0-only',
        '// GENERATED by tools/grain/tiles.py -- do not edit.',
        f'// Generator SHA-256 (LF line ends): {hashlib.sha256(src).hexdigest()}',
        '// Grain v2 tables (tools/grain/grain.c): per size (small, large) a 128 x 128 luma tile, a 128 x 64',
        '// (Cb, Cr) colour tile (signed bytes, standard deviation 32 = one unit) and a 256-byte',
        '// brightness table (128 = the strength at mid grey).',
        '',
        f'export const GRAIN_TILE_SIZE = {N};',
        'const b = (s: string): Uint8Array => Uint8Array.from(atob(s), c => c.charCodeAt(0));',
        'export const GRAIN_LUMA_TILES: readonly Uint8Array[] = [',
        *[f"  b('{b64(p[0])}')," for p in parts], '];',
        'export const GRAIN_COLOUR_TILES: readonly Uint8Array[] = [',
        *[f"  b('{b64(p[1])}')," for p in parts], '];',
        'export const GRAIN_TONES: readonly Uint8Array[] = [',
        *[f"  b('{b64(p[2])}')," for p in parts], '];',
        '',
    ]
    OUT.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print('\n'.join(stats))
    print(OUT, OUT.stat().st_size, 'bytes')


if __name__ == '__main__':
    main()
