"""Compile tools/grain/grain.c and write core/src/fw/gr3x/grain-code.ts.

As tools/halation/gen.py: the module is position independent (-fropi -frwpi, no global data, every
address passed in through its context argument), checked by linking it at two addresses and
comparing. Compiler: clang if present, else `python3 -m ziglang cc` (pip install ziglang; GRMOD_ZIG=1
uses it even when clang is installed). The ELF checks use pyelftools (pip install pyelftools), so no
binutils are needed.
"""
import base64
import hashlib
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from elftools.elf.elffile import ELFFile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SRC = HERE / 'grain.c'
OUT = ROOT / 'core' / 'src' / 'fw' / 'gr3x' / 'grain-code.ts'
USE_ZIG = bool(os.environ.get('GRMOD_ZIG')) or not (shutil.which('clang') and shutil.which('ld.lld') and shutil.which('llvm-objcopy'))
FLAGS = ['-mcpu=cortex_a9' if USE_ZIG else '-mcpu=cortex-a9', '-marm', '-mfloat-abi=soft', '-Os',
         '-ffreestanding', '-fno-builtin', '-fno-unwind-tables', '-fno-asynchronous-unwind-tables', '-nostdlib',
         '-fropi', '-frwpi', '-fno-jump-tables', '-Wall', '-Wextra', '-Werror']


def tools():
    if not USE_ZIG:
        return ['clang', '-target', 'armv7-none-eabi'], ['ld.lld'], ['llvm-objcopy']
    z = [sys.executable, '-m', 'ziglang']
    return z + ['cc', '-target', 'arm-freestanding-eabi'], z + ['ld.lld'], z + ['objcopy']


def run(cmd):
    r = subprocess.run([str(c) for c in cmd], capture_output=True, text=True)
    if r.returncode:
        sys.exit(f'{" ".join(map(str, cmd))}\n{r.stdout}{r.stderr}')
    return r.stdout


def build(cc, ld, objcopy, tmp, origin):
    obj = tmp / 'gr.o'
    run(cc + FLAGS + ['-c', SRC, '-o', obj])
    elf = tmp / f'gr_{origin:x}.elf'
    run(ld + [f'-Ttext=0x{origin:x}', '--entry=grain', '-o', elf, obj])
    out = tmp / f'gr_{origin:x}.bin'
    run(objcopy + ['-O', 'binary', '-j', '.text', elf, out])
    with open(elf, 'rb') as f:
        e = ELFFile(f)
        for s in e.iter_sections():
            if s.name.startswith(('.data', '.bss', '.rodata', '.got')) and s['sh_size']:
                sys.exit(f'module has a {s.name} section')
        sym = e.get_section_by_name('.symtab').get_symbol_by_name('grain')
        if not sym or sym[0]['st_value'] != origin:
            sys.exit('grain is not at the start of .text')
    return out.read_bytes()


def main():
    cc, ld, objcopy = tools()
    with tempfile.TemporaryDirectory() as t:
        tmp = Path(t)
        a = build(cc, ld, objcopy, tmp, 0x10000)
        b = build(cc, ld, objcopy, tmp, 0x543f0000)
    if a != b:
        sys.exit('module is not position independent')
    while len(a) % 4:
        a += b'\0'
    version = run(cc + ['--version']).splitlines()[0]
    src_hash = hashlib.sha256(SRC.read_bytes().replace(b'\r\n', b'\n')).hexdigest()
    OUT.write_text(
        '// SPDX-License-Identifier: GPL-2.0-only\n'
        '// GENERATED by tools/grain/gen.py from tools/grain/grain.c -- do not edit.\n'
        f'// Compiler: {version}\n'
        f'// Source SHA-256 (LF line ends): {src_hash}\n'
        '// Position independent: entry `grain(ctx, config)` at offset 0.\n\n'
        f"export const GRAIN_CODE = '{base64.b64encode(a).decode()}';\n"
        f'export const GRAIN_CODE_LENGTH = {len(a)};\n'
        f"export const GRAIN_SOURCE_SHA256 = '{src_hash}';\n", encoding='utf-8', newline='\n')
    print(f'{OUT}: {len(a)} bytes')


if __name__ == '__main__':
    main()
