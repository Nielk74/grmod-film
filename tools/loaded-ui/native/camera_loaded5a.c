/* ---------------------------------------------------------------- the selected film
 * Read, never written, from the UI task: the settings object (UserDataModel, the singleton 0x5320b31c returns,
 * 0x55063f30) holds a pointer to the record in use at +4. Byte 0x44 of the record is the movie flag, 0x1c0 the
 * active Image Control set (0..2) and 0x1c2 + 2*set that set's look: the camera's own looks are 11..22, the
 * film pack's film k is look 64 + k. The film pack's native modules read the same bytes (tools/gr3x/native). */
#define USERDATA_MODEL 0x55063f30u
/* Pack film k (look 64 + k) as a Loaded film: ld_film_of_slot, generated at link time from the film names read out of
 * the base image (the linker refuses a base with a film Loaded does not have). */
uint32_t loaded_film_of_look(uint32_t look){
    if(look>=64u&&look<64u+LD_SLOTS)return ld_film_of_slot[look-64u];
    return LD_FILMS-1u;   /* the camera's own looks and anything unknown: the neutral GR III strip */
}
/* 0..LD_FILMS-1, or 0xffffffff when the settings cannot be read as expected (no animation then). */
uint32_t loaded_selected_film(void){
    const uint8_t *model=(const uint8_t *)(uintptr_t)USERDATA_MODEL,*rec;
    uintptr_t at;uint32_t set;
    rec=(const uint8_t *)ptr(model,4);at=(uintptr_t)rec;
    /* As the film pack's own readers (films.c record_of): a null record means not initialised; no other validation exists. */
    if(!rec||(at&3u))return 0xffffffffu;
    if(rec[0x44]!=0)return 0xffffffffu;           /* movie mode: not a still-shot moment */
    set=rec[0x1c0];if(set>2u)return 0xffffffffu;
    return loaded_film_of_look(rec[0x1c2+2u*set]);
}

/* ---------------------------------------------------------------- allocation: all or nothing */
static void release(Adapter *s){
    uint32_t i;
    for(i=0;i<NV;i++)if(s->pixels[i]){heap_free(s->pixels[i]);s->pixels[i]=0;}
}
static Adapter *create(void){
    Adapter *s=state();uint32_t i,bytes;
    if(s)return s;
    s=(Adapter *)heap_alloc(sizeof(*s));if(!s)return 0;
    for(i=0;i<sizeof(*s)/4u;i++)((volatile uint32_t *)s)[i]=0;
    for(i=0;i<NV;i++){
        bytes=view_pixels(i)*4u;
        s->pixels[i]=(uint32_t *)heap_alloc(bytes);
        if(!s->pixels[i]){release(s);heap_free(s);return 0;}   /* a failure of any piece frees everything */
        s->buffers.pixels[VIEW_ID[i]]=s->pixels[i];
        s->buffers.stride[VIEW_ID[i]]=loaded_view_rect[VIEW_ID[i]][2];
        s->buffers.capacity[VIEW_ID[i]]=view_pixels(i);
        s->bitmaps[i].width=loaded_view_rect[VIEW_ID[i]][2];s->bitmaps[i].height=loaded_view_rect[VIEW_ID[i]][3];
    }
    s->bitmaps[FULLI].width=loaded_view_rect[LOADED_V_FULL][2];s->bitmaps[FULLI].height=loaded_view_rect[LOADED_V_FULL][3];
    for(i=0;i<24;i++)s->view_vtable[i]=((const uint32_t *)(uintptr_t)0x53c0a8a0u)[i];
    s->view_vtable[2+0x4c/4]=(uint32_t)(uintptr_t)grmod_draw;
    s->timer_vtable[0]=(uint32_t)(uintptr_t)listener_noop;
    s->timer_vtable[1]=(uint32_t)(uintptr_t)listener_noop;
    s->timer_vtable[2]=(uint32_t)(uintptr_t)grmod_timer_expired;
    s->listener.vtable=s->timer_vtable;
    s->timer_model=timer_get();
    loaded_init(&s->engine);
    for(i=0;i<LD_FILMS;i++){s->nframes[i]=1;s->rolls[i]=1;}
    s->magic=MAGIC;
    __asm__ volatile("dmb ish" ::: "memory");
    grmod_adapter_state=s;return s;
}

/* ---------------------------------------------------------------- native tree (as camera_gr3.c, per view) */
static void *find_root(void **owner){
    void *app=app_get(),*model,*c,*root;uint32_t vt;
    if(!app)return 0;model=model_get(app);if(!model)return 0;
    c=controller_get(model);if(!c)return 0;vt=rd32(c);
    if(vt!=0x53b2f9e8u&&vt!=0x53b41380u)return 0;
    root=ptr(c,0x15c);if(!root||rd32(root)!=0x53c09f10u)return 0;
    if(canvas_slot(c,0)!=root&&canvas_slot(c,3)!=root)return 0;
    *owner=c;return root;
}
static int child_vector(void *root,uint32_t **begin,uint32_t **end){
    uintptr_t b=(uintptr_t)ptr(root,0xc),e=(uintptr_t)ptr(root,0x10),cap=(uintptr_t)ptr(root,0x14);
    if((b|e|cap)&3u)return 0;
    if(!b){*begin=0;*end=0;return !e&&!cap;}
    if(e<b||cap<e||cap-b>16384u)return 0;
    *begin=(uint32_t *)b;*end=(uint32_t *)e;return 1;
}
/* The views are removed in the order they were added; only the ones that are attached (the att bits). */
static void detach(Adapter *s){
    void *root=s->root;uint32_t *it,*end,i;
    if(!root)return;
    for(i=0;i<NVA;i++){
        void *v=s->views[i];if(!v||!(s->att&(1u<<i)))continue;
        view_visible(v,0);
        /* the vector is re-read for each view: erasing moves the later children */
        if(child_vector(root,&it,&end))for(;it!=end;it++)if(*it==(uint32_t)(uintptr_t)v){
            vector_erase((uint8_t *)root+8,it);break;
        }
        view_parent(v,0);
    }
    s->att=0;
    view_invalidate(root);s->root=0;s->controller=0;
}
/* The full-screen view is added FIRST (lowest z-order, as in the lab) so the counter and the bands stay on top of the sheet. */
static int make_view(Adapter *s,uint32_t i){
    uint32_t descriptor[6];const uint16_t *r=loaded_view_rect[VIEW_ID[i]];
    if(s->views[i])return 1;                         /* created views are kept for the next time */
    descriptor[0]=10;descriptor[1]=r[0];descriptor[2]=r[1];descriptor[3]=r[2];descriptor[4]=r[3];descriptor[5]=0;
    s->views[i]=view_factory((void *)descriptor);
    if(!s->views[i])return 0;
    *(uint32_t **)s->views[i]=s->view_vtable+2;view_visible(s->views[i],0);
    return 1;
}
static int attach(Adapter *s,void *root,void *controller){
    uint32_t *begin,*end,i,order[NVA],n=0,first;
    if(s->root==root&&s->controller==controller)return 1;
    detach(s);
    if(!child_vector(root,&begin,&end))return 0;
    if(s->want_full)order[n++]=FULLI;
    for(i=0;i<NV;i++)order[n++]=i;
    for(i=0;i<n;i++)if(!make_view(s,order[i]))return 0;
    /* Our detached objects must not already belong to a different native tree. */
    for(i=0;i<n;i++)if(ptr(s->views[order[i]],4))return 0;
    for(i=0;i<n;i++){view_add(root,s->views[order[i]]);s->att|=1u<<order[i];}
    s->root=root;s->controller=controller;
    for(i=0;i<n;i++)view_visible(s->views[order[i]],1);
    /* A new child is only laid out (its absolute rectangle computed) if its ancestors are flagged "a child needs layout". A fresh view
     * already carries its own flag, so view_visible does not propagate it, and a clean root never visits it: its rectangle stays 0,0,0,0 and
     * every draw is rejected. Ask the root explicitly, through its own vtable slot 0x20 (0x533ab3cc, the same request view_visible makes). */
    first=order[0];
    ((two_fn)(uintptr_t)(*(uint32_t **)root)[8])(root,s->views[first]);
    view_invalidate(root);return 1;
}
/* Take the views off and put them back, with or without the full-screen view. 0 if the attach failed (nothing is attached then). */
static int relayer(Adapter *s,void *root,void *controller,uint32_t with_full){
    detach(s);s->want_full=with_full;
    return attach(s,root,controller);
}

static void disarm(Adapter *s){
    uint32_t id=s->timer_id;s->timer_id=0;
    if(id&&s->timer_model)timer_stop(s->timer_model,id);
}
static void arm(Adapter *s,uint32_t now){
    uint32_t delay=s->sheet?SHEET_TICK_MS:33,elapsed,dur;
    if(s->timer_id||s->transition||!(s->running||s->sliding))return;
    if(s->running&&s->engine.active){   /* tick exactly at the moment's deadline */
        elapsed=now-s->engine.start;dur=loaded_duration(s->params.film,s->engine.moment);
        if(elapsed<dur&&dur-elapsed<delay)delay=dur-elapsed?dur-elapsed:1;
    }
    if(s->timer_model)s->timer_id=timer_start(s->timer_model,delay,&s->listener);
}

/* ---------------------------------------------------------------- the contact sheet (tier 2, design A) */
/* Free the buffer and forget the sheet. The full-screen view must already be off the tree: nothing draws from the buffer any more. */
static void sheet_free(Adapter *s){
    uint32_t *b=s->full;
    s->sheet=0;s->sheet_ready=0;s->want_full=0;s->full=0;
    s->buffers.pixels[LOADED_V_FULL]=0;s->buffers.stride[LOADED_V_FULL]=0;s->buffers.capacity[LOADED_V_FULL]=0;
    s->params.tier=1;
    if(b)heap_free(b);
}
/* The sheet is over or replaced while the live view is still up: the four small views go back on their own, the buffer is freed. */
static void sheet_leave(Adapter *s){
    void *root=s->root,*controller=s->controller;
    if(!s->sheet&&!s->full)return;
    if(root){if(!relayer(s,root,controller,0)){s->shown=0;s->hides++;}}
    sheet_free(s);
}
/* One attempt: the buffer, then the view on the tree below the four small ones. 1 = the sheet may start; 0 = skipped, everything as before. */
static int sheet_begin(Adapter *s,void *root,void *controller){
    s->full=(uint32_t *)heap_alloc(SHEET_BYTES);
    if(!s->full){s->sheet_alloc_fail++;return 0;}
    if(!relayer(s,root,controller,1)){
        s->sheet_view_fail++;
        sheet_free(s);
        if(!relayer(s,root,controller,0)){s->shown=0;s->hides++;}   /* the four small views back; if even that fails they come back at the next transition */
        return 0;
    }
    s->buffers.pixels[LOADED_V_FULL]=s->full;s->buffers.stride[LOADED_V_FULL]=loaded_view_rect[LOADED_V_FULL][2];
    s->buffers.capacity[LOADED_V_FULL]=loaded_view_rect[LOADED_V_FULL][2]*loaded_view_rect[LOADED_V_FULL][3];
    s->sheet=1;s->sheet_ready=0;
    return 1;
}

/* Hide everything: stop the timer, drop the moment, detach the views, free the sheet. */
static void hide(Adapter *s){
    disarm(s);loaded_cancel(&s->engine);s->pending_roll=0;s->running=0;s->sliding=0;
    if(s->sheet)s->sheet_cancels++;
    if(s->shown){detach(s);s->shown=0;s->hides++;}
    if(s->sheet||s->full)sheet_free(s);
}
static void stop_all(void){Adapter *s=state();if(s)hide(s);}
/* The release hook: in the field data it fires together with the completion, not at the press, so it must not touch the views. */
void grmod_cancel(void){}

/* The permanent state: the tab and the counter, drawn by the reference renderer's live render (peek: the slide-in clock, 1000 = sitting there). */
static void render_steady(Adapter *s,int32_t peek){
    loaded_params p;
    p.moment=LOADED_LIVE;p.film=s->film;p.frame=s->nframes[s->film];p.roll=s->rolls[s->film];p.tier=1;
    p.tab_mode=LOADED_PEEK;p.counter_mode=LOADED_PEEK;p.peek_ms=peek;p.tab_peek_ms=-2;p.counter_peek_ms=-2;
    p.month=12;p.year=0;p.thumbs=0;p.circled=-1;p.hold=0;
    if(loaded_render(&s->engine,&s->buffers,&p,0)<0){hide(s);return;}
    s->engine.sig_valid=0;     /* the pure render overwrote the furniture buffers: the engine's per-view cache no longer describes them (a load starting after the last tick's hidden state would skip the tab) */
    if(s->root)view_invalidate(s->root);
}
/* A new film is a new roll: the counter goes back to 1 and the roll number advances. */
#define NEUTRAL_FILM (LD_FILMS-1u)   /* the neutral GR III strip: the camera's own looks */
static void note_film(Adapter *s,uint32_t film){
    if(s->have_film&&film!=s->film)s->film_changes++;      /* each film keeps its own count: nothing is reset */
    s->film=film;s->have_film=1;
}

static void update(Adapter *s,uint32_t now){
    void *controller=0,*root;int r;
    if(s->running||s->sliding){
        root=find_root(&controller);
        if(!root||!attach(s,root,controller)){hide(s);return;}
        if(s->running){
            /* Frame 36: the end of the roll follows its shot without a break (the tab and counter are already showing). */
            if(s->pending_roll&&s->engine.active&&now-s->engine.start>=loaded_duration(s->params.film,s->engine.moment)){
                s->pending_roll=0;                                   /* one attempt per roll end */
                if(!sheet_begin(s,root,controller)){                 /* skipped: the counter and tab come back at frame 1 of the next roll */
                    loaded_cancel(&s->engine);s->running=0;
                    if(s->shown)render_steady(s,1000);
                    arm(s,now);return;
                }
                if(!grmod_clock_ms(&now)){hide(s);return;}           /* the first full-screen attach may take time */
                s->params.moment=LOADED_ROLL;s->params.hold=1;s->params.tier=2;
                if(loaded_start(&s->engine,&s->params,now)!=0){hide(s);return;}
                s->engine.sig_valid=0;s->sheets++;
            }
            r=loaded_tick(&s->engine,&s->buffers,now);
            if(r<0){hide(s);return;}
            if(s->sheet)s->sheet_ready=1;
            if(!(r&0x100)){
                if(s->sheet){sheet_leave(s);s->sheet_ends++;}        /* over: the sheet goes, its buffer is freed */
                loaded_cancel(&s->engine);s->running=0;s->pending_roll=0;
                if(s->shown)render_steady(s,1000);                   /* the tab and counter stay, with the new number */
            }
            else if(r&0x1f)view_invalidate(root);
        }else{
            uint32_t pe=now-s->slide_start;
            if(pe>=180u){s->sliding=0;render_steady(s,1000);}else render_steady(s,(int32_t)pe);
        }
    }
    arm(s,now);
}

/* Show the permanent views: the slide-in, then nothing more until something changes. */
/* The film-load moment for a new film: the same four small views, tier 1. The counter lands on the film's own number. */
static int start_load(Adapter *s,uint32_t film,uint32_t now){
    loaded_params *p=&s->params;
    p->moment=LOADED_LOAD;p->film=film;p->frame=s->nframes[film];p->roll=s->rolls[film];p->tier=1;
    p->tab_mode=LOADED_PEEK;p->counter_mode=LOADED_PEEK;p->peek_ms=-1;p->tab_peek_ms=-2;p->counter_peek_ms=-2;
    p->month=12;p->year=0;p->thumbs=0;p->circled=-1;p->hold=0;
    s->pending_roll=0;
    loaded_cancel(&s->engine);
    if(loaded_start(&s->engine,p,now)!=0)return 0;
    s->engine.sig_valid=0;
    s->sliding=0;s->running=1;s->loads++;
    return 1;
}
static int show(Adapter *s,void *root,void *controller,uint32_t now){
    uint32_t film=loaded_selected_film(),changed;
    if(film==0xffffffffu){hide(s);return 0;}                  /* movie mode or unreadable settings: nothing */
    changed=s->have_film&&film!=s->film;                     /* decided before the film is recorded: a failed attach keeps the change for the next try */
    if(!attach(s,root,controller)){s->attach_failures++;return 0;}
    note_film(s,film);
    s->shown=1;s->shows++;
    if(changed&&film!=NEUTRAL_FILM&&start_load(s,film,now)){update(s,now);return s->shown;}
    s->sliding=1;s->slide_start=now;
    render_steady(s,0);
    if(s->shown)arm(s,now);
    return s->shown;
}
/* After a transition or an allocation: show them if the shooting live view is up. */
static void try_show(Adapter *s){
    void *controller=0,*root;uint32_t now;
    if(s->shown||s->transition)return;
    if(!grmod_clock_ms(&now))return;
    root=find_root(&controller);
    if(!root||rd32(controller)!=0x53b2f9e8u)return;          /* only the shooting live view */
    show(s,root,controller,now);
}

/* Start the animation for one photo; 1 if it is running. The block is created here when it does not exist yet (all or nothing). */
static int start_shot(void){
    Adapter *s;void *controller=0,*root;uint32_t now,film,frame,held,sliding;
    if(!grmod_clock_ms(&now)){stop_all();return 0;}
    root=find_root(&controller);if(!root){stop_all();return 0;}
    film=loaded_selected_film();if(film==0xffffffffu){stop_all();return 0;}
    s=create();if(!s)return 0;
    if(s->sheet){s->sheet_cancels++;sheet_leave(s);}    /* the shutter has priority: a photo during the sheet ends it at once */
    disarm(s);s->transition=0;
    note_film(s,film);
    sliding=s->sliding;held=s->shown&&!sliding;      /* the tab and counter are already showing: no new slide-in */
    frame=s->nframes[film];
    s->params.moment=LOADED_SHOT;s->params.film=film;s->params.frame=frame;s->params.roll=s->rolls[film];
    s->nframes[film]=frame>=ROLL_LEN?1u:frame+1u;
    if(frame>=ROLL_LEN)s->rolls[film]++;
    s->shots++;
    s->params.tier=1;s->params.tab_mode=LOADED_PEEK;s->params.counter_mode=LOADED_PEEK;
    s->params.peek_ms=-1;s->params.tab_peek_ms=-2;s->params.counter_peek_ms=-2;
    s->params.month=12;s->params.year=0;s->params.thumbs=0;s->params.circled=-1;s->params.hold=held;
    s->pending_roll=frame==ROLL_LEN;
    if(!attach(s,root,controller)){hide(s);return 0;}
    /* First-load native construction may take time: the clock is read again just before the first render. */
    if(!grmod_clock_ms(&now)){hide(s);return 0;}
    loaded_cancel(&s->engine);
    if(loaded_start(&s->engine,&s->params,now)!=0){hide(s);return 0;}
    s->engine.sig_valid=0;
    if(sliding)loaded_peek(&s->engine,s->slide_start);   /* the slide-in goes on seamlessly under the moment */
    else if(!held)loaded_peek(&s->engine,now);           /* nothing showing yet: the tab and counter slide in with the photo */
    if(!s->shown){s->shown=1;s->shows++;}
    s->sliding=0;s->running=1;
    update(s,now);
    return s->running;
}

/* The completion hook (0x532d55f8): consume the acceptance of this photo, or start late when there was none. */
void grmod_on_shot(void){
    Adapter *s=state();uint32_t now=0,i;
    if(s&&grmod_clock_ms(&now)){
        while(s->npend&&now-s->pend[0]>PENDING_MS){          /* an acceptance older than 40 s belongs to no completion */
            for(i=1;i<s->npend;i++)s->pend[i-1u]=s->pend[i];
            s->npend--;s->dropped++;
        }
        if(s->npend){
            for(i=1;i<s->npend;i++)s->pend[i-1u]=s->pend[i];
            s->npend--;s->consumed++;
            return;
        }
    }
    if(start_shot()){s=state();if(s)s->fallbacks++;}
}

/* The capture signal: a clock value in a spare RAM word, so it exists before the block does. */
static void note_signal(void){
    uint32_t now=0;
    if(grmod_clock_ms(&now))grmod_signal_time=now|1u;
}
/* A 0x013E: a photo only after a capture signal (and not within 2 s of an accepted one). */
static void accepted_key(void){
    Adapter *s=state();uint32_t now=0,sig;
    if(!grmod_clock_ms(&now))return;
    if(s&&s->has_accept&&now-s->last_accept<IGNORE_MS){s->ignored++;return;}
    sig=grmod_signal_time;
    if(!sig||now-sig>SIGNAL_MS){                     /* the return from playback, or a signal too old: not a photo */
        if(s){if(sig)s->rej_stale++;else s->rej_nosignal++;}
        return;
    }
    grmod_signal_time=0;                              /* one signal, one photo */
    if(!s){                                         /* the same hook and task as the idle allocation, but a photo was just taken: the camera is up */
        if(grmod_alloc_flag)return;
        s=create();
        if(!s){grmod_alloc_flag=1;return;}
    }
    s->last_accept=now;s->has_accept=1;s->accepts++;
    if(!start_shot())return;
    s=state();
    if(s){
        if(s->npend>=4u){uint32_t i;for(i=1;i<4u;i++)s->pend[i-1u]=s->pend[i];s->npend=3u;s->dropped++;}
        s->pend[s->npend++]=now;
    }
}
/* No block yet: count UI events until the camera has certainly been up a while (5000 events, about 20 s, and 20 s on the OS clock), then allocate once. */
static void idle(void){
    uint32_t n,now=0;
    if(grmod_alloc_flag)return;
    n=grmod_armed_flag+1u;grmod_armed_flag=n;
    if(n<ARM_EVENTS)return;
    if(!grmod_clock_ms(&now)||now<ARM_MS)return;
    if(!create()){grmod_alloc_flag=1;return;}
    {Adapter *s=state();if(s)try_show(s);}
}
/* The sixth hook: every UI event the camera dispatches. The fast path is one compare and one load. */
void grmod_on_event(void *app,const uint16_t *event){
    (void)app;
    if(event[0]==KEY_EVENT){accepted_key();return;}
    if(event[0]==CAPTURE_EVENT){note_signal();return;}
    if(grmod_adapter_state)return;
    idle();
}

void grmod_timer_expired(void *listener,uint32_t id){
    Adapter *s=state();uint32_t now;
    if(!s||listener!=&s->listener||!id||id!=s->timer_id)return;
    s->timer_id=0;
    if(s->transition)return;
    if(!grmod_clock_ms(&now)){stop_all();return;}
    update(s,now);
}

void grmod_before_transition(void *old_controller,uint32_t destination_id){
    Adapter *s=state();uint32_t id=destination_id-0x08000000u;(void)old_controller;
    /* A capture signal does not survive a transition to a menu or playback (the ids 0..2 and 0x0c..0x11 are the shooting controllers: the live view
     * and quick review chain of a photo with quick review on must not lose its signal). */
    if(!(id<=2u||(id>=0x0cu&&id<=0x11u))&&grmod_signal_time){grmod_signal_time=0;if(s)s->sig_cleared++;}
    if(!s)return;
    ++s->transition;hide(s);                                 /* every controller change hides them: only the shooting live view shows them */
}
void grmod_after_transition(void){
    Adapter *s=state();if(!s||!s->transition)return;
    if(--s->transition)return;
    try_show(s);                                             /* back in the shooting live view: with the slide-in */
}
void grmod_before_canvas_delete(void *root){
    Adapter *s=state();if(s&&s->root==root)hide(s);
}
void grmod_before_audio_shutdown(void){}

static int32_t maximum(int32_t a,int32_t b){return a>b?a:b;}
static int32_t minimum(int32_t a,int32_t b){return a<b?a:b;}

void grmod_draw(void *view,void *surface){
    static const uint8_t context[8]={0,0,0,0,0,0,0,0};
    Adapter *s=state();const int32_t *absolute,*clip;uint32_t stride,height,width,visible_h,capacity,i,v;
    int32_t x0,y0,x1,y1,sx,sy,vw,vh;uintptr_t pixels;
    if(!s||!surface||!s->root||!s->shown||s->transition)goto finish;
    for(i=0;i<NVA;i++)if(s->views[i]==view)break;
    if(i==NVA)goto finish;
    v=VIEW_ID[i];
    if(i==FULLI&&(!s->sheet||!s->sheet_ready||!s->full))goto finish;
    if(!(s->engine.dirty&(1u<<v)))goto finish;                      /* nothing visible in this view */
    vw=(int32_t)loaded_view_rect[v][2];vh=(int32_t)loaded_view_rect[v][3];
    if(!byte(view,0x9e)||ptr(view,4)!=s->root||ptr(s->root,0xec)!=surface||byte(surface,2)!=5)goto finish;
    stride=half(surface,0x18);height=half(surface,0x1a);
    width=half(surface,0x1c);visible_h=half(surface,0x1e);pixels=(uintptr_t)ptr(surface,8);
    if(!stride||stride>4096||!height||height>4096||!width||width>stride||!visible_h||visible_h>height||
       !pixels||(pixels&3u))goto finish;
    capacity=stride*height*4u;if(pixels>0xffffffffu-capacity)goto finish;
    absolute=(const int32_t *)((const uint8_t *)view+0x30);
    clip=(const int32_t *)((const uint8_t *)view+0x64);
    if(absolute[0]<-4096||absolute[0]>4096||absolute[1]<-4096||absolute[1]>4096||
       absolute[2]!=vw||absolute[3]!=vh||
       clip[0]<-4096||clip[0]>4096||clip[1]<-4096||clip[1]>4096||
       clip[2]<=0||clip[2]>4096||clip[3]<=0||clip[3]>4096)goto finish;
    x0=maximum(maximum(absolute[0],clip[0]),0);y0=maximum(maximum(absolute[1],clip[1]),0);
    x1=minimum(minimum(absolute[0]+vw,clip[0]+clip[2]),(int32_t)width);
    y1=minimum(minimum(absolute[1]+vh,clip[1]+clip[3]),(int32_t)visible_h);
    sx=x0-absolute[0];sy=y0-absolute[1];
    if(x1<=x0||y1<=y0||sx<0||sy<0||sx+x1-x0>vw||sy+y1-y0>vh)goto finish;
    NATIVE(copy_fn,0x5320a020u)(context,surface,absolute[0],absolute[1],
        (uint32_t)sx,(uint32_t)sy,(uint32_t)(x1-x0),(uint32_t)(y1-y0),&s->bitmaps[i],i==FULLI?s->full:s->pixels[i]);
finish:
    base_draw(view,surface);
}
