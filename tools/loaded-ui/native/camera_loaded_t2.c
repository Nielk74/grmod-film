    static const uint8_t context[8]={0,0,0,0,0,0,0,0};
    void *root=ptr(view,4);const int32_t *absolute,*clip;
    uint32_t stride,height,width,visible_h,capacity;uintptr_t pixels;int32_t ax,ay,x0,y0,x1,y1;
    if(!root||!surface||ptr(root,0xec)!=surface){t->rej=7;return 0;}
    if(!byte(view,0x9e)){t->rej=5;return 0;}
    if(byte(surface,2)!=5){t->rej=8;return 0;}
    stride=half(surface,0x18);height=half(surface,0x1a);width=half(surface,0x1c);visible_h=half(surface,0x1e);pixels=(uintptr_t)ptr(surface,8);
    if(!stride||stride>4096||!height||height>4096||!width||width>stride||!visible_h||visible_h>height||!pixels||(pixels&3u)){t->rej=9;return 0;}
    capacity=stride*height*4u;if(pixels>0xffffffffu-capacity){t->rej=10;return 0;}
