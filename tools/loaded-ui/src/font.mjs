export const GLYPH_CHARS = Object.keys(SRC).join('');
export const GLYPH_W = 5, GLYPH_H = 7;
/** Packed data: 7 bytes per glyph, bit 4 = leftmost column. This is the whole font asset. */
export const FONT_DATA = new Uint8Array(GLYPH_CHARS.length * GLYPH_H);
export const FONT_INDEX = new Int8Array(256).fill(-1);
GLYPH_CHARS.split('').forEach((ch, g) => {
  FONT_INDEX[ch.charCodeAt(0)] = g;
  SRC[ch].split('/').forEach((row, y) => {
    let b = 0;
    for (let x = 0; x < 5; x++) b = (b << 1) | (row[x] === '#' ? 1 : 0);
    FONT_DATA[g * GLYPH_H + y] = b;
  });
});
