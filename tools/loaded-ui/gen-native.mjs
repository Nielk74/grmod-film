// Generates native/loaded_data.h from the JS reference modules: the single source of truth for every table.
// Usage: node gen-native.mjs [--check]   (--check fails if the committed header differs)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { FONT_DATA, FONT_INDEX, GLYPH_CHARS, COUNTER_DATA } from './src/font.mjs';
import { BAYER } from './src/surface.mjs';
import { FILMS, ROLL_LENGTH } from './src/films.mjs';
import { VIEWS, SHOT_MS, LOAD_MS, ROLL_MS, PEEK_MS } from './src/plan.mjs';
import { GEOM } from './src/renderer.mjs';

const KIND = { neg: 0, bw: 1, slide: 2, instant: 3, cine: 4 };
const arr = (a, per = 16) => { const l = Array.from(a); let o = ''; for (let i = 0; i < l.length; i += per) o += '  ' + l.slice(i, i + per).join(', ') + ',\n'; return o; };
const str = s => '"' + s + '"';
let h = '/* Generated by gen-native.mjs from the JS reference. Do not edit. */\n#ifndef LOADED_DATA_H\n#define LOADED_DATA_H\n#include <stdint.h>\n\n';
h += `#define LD_FILMS ${FILMS.length}\n#define LD_ROLL_LENGTH ${ROLL_LENGTH}\n#define LD_PEEK_MS ${PEEK_MS}\n`;
h += `#define LD_SHOT_NEG ${SHOT_MS.neg}\n#define LD_SHOT_BW ${SHOT_MS.bw}\n#define LD_SHOT_CINE ${SHOT_MS.cine}\n#define LD_SHOT_SLIDE ${SHOT_MS.slide}\n#define LD_SHOT_INSTANT ${SHOT_MS.instant}\n#define LD_LOAD_MS ${LOAD_MS}\n#define LD_ROLL_MS ${ROLL_MS}\n`;
for (const k of ['CELL', 'PITCH', 'HOLE_W', 'HOLE_H', 'HOLE_X0', 'CINE_PITCH', 'CINE_HW', 'CINE_HH', 'REST_CELL']) h += `#define LD_${k} ${GEOM[k]}\n`;
for (const [k, v] of Object.entries(GEOM.SHEET)) h += `#define LD_SHEET_${k.toUpperCase()} ${v}\n`;
h += `#define LD_LOAD_ROLL_A ${GEOM.LOAD_ROLL[0]}\n#define LD_LOAD_ROLL_B ${GEOM.LOAD_ROLL[1]}\n#define LD_REWIND_A ${GEOM.REWIND[0]}\n#define LD_REWIND_B ${GEOM.REWIND[1]}\n`;
h += `#define LD_DEFAULT_MONTH ${GEOM.DEFAULT_DATE.month}\n#define LD_DEFAULT_YEAR ${GEOM.DEFAULT_DATE.year}\n\n`;
h += `/* shot counter roll window (ms) by kind: neg, bw, slide, instant, cine */\nstatic const uint16_t ld_roll_win[5][2] = {\n`;
for (const k of ['neg', 'bw', 'slide', 'instant', 'cine']) h += `  { ${GEOM.ROLL_WIN[k][0]}, ${GEOM.ROLL_WIN[k][1]} },\n`;
h += '};\n\n';
h += `#define LD_VIEW_RECTS { ${VIEWS.map(v => `{ ${v.x}, ${v.y}, ${v.w}, ${v.h} }`).join(', ')} }
`;
h += `typedef struct { uint16_t x, y, w, h; uint8_t tier, furniture; } ld_view;\nstatic const ld_view ld_views[${VIEWS.length}] = {\n`;
for (const v of VIEWS) h += `  { ${v.x}, ${v.y}, ${v.w}, ${v.h}, ${v.tier}, ${v.role === 'furniture' ? 1 : 0} }, /* ${v.id} */\n`;
h += '};\n\n';
h += `typedef struct { const char *label, *caption, *code; uint8_t label_len, kind; uint8_t edge[3], panel[3], band[3], ink[3], cink[3]; } ld_film;\nstatic const ld_film ld_films[${FILMS.length}] = {\n`;
for (const f of FILMS) h += `  { ${str(f.label)}, ${str(f.caption)}, ${str(f.code)}, ${f.label.length}, ${KIND[f.kind]}, {${f.edge}}, {${f.panel}}, {${f.band}}, {${f.ink}}, {${f.captionInk}} }, /* ${f.name} */\n`;
h += '};\n\n';
h += `/* 5x7 font: ${GLYPH_CHARS.length} glyphs x 7 rows (bit 4 = left column); ld_font_index maps a char code to a glyph or -1 */\nstatic const uint8_t ld_font_data[${FONT_DATA.length}] = {\n${arr(FONT_DATA, 14)}};\n`;
h += `static const int8_t ld_font_index[256] = {\n${arr(FONT_INDEX, 16)}};\n\n`;
h += `/* counter digits: 12 glyphs (0-9, blank, S) x 11 rows of 7 bits (bit 6 = left) */\nstatic const uint8_t ld_counter_data[${COUNTER_DATA.length}] = {\n${arr(COUNTER_DATA, 11)}};\n\n`;
h += `static const uint8_t ld_bayer[16] = {\n${arr(BAYER, 16)}};\n`;
h += `static const char ld_months[] = "JANFEBMARAPRMAYJUNJULAUGSEPOCTNOVDEC";\n\n#endif\n`;
const out = fileURLToPath(new URL('native/loaded_data.h', import.meta.url));
if (process.argv.includes('--check')) {
  const have = existsSync(out) ? readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
  if (have !== h) { console.error('native/loaded_data.h is out of date: run node gen-native.mjs'); process.exit(1); }
  console.log('native/loaded_data.h is up to date');
} else { writeFileSync(out, h, 'utf8'); console.log('wrote', out, h.length, 'bytes'); }
