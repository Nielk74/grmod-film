// Extracts the 20 films (name, group, caption, code, icon colours) from core/src/filmpack/looks.ts
// into src/films.gen.mjs. The packaging colours are the ones the film icons already use.
import { readFileSync, writeFileSync } from 'node:fs';
const here = new URL('.', import.meta.url);
const src = readFileSync(new URL('../../core/src/filmpack/looks.ts', here), 'utf8');
const re = /name: '([^']+)', group: '(\w+)', caption: '([^']+)', code: '([^']+)',\s*colors: \{ panel: \[([\d, ]+)\], band: \[([\d, ]+)\], ink: \[([\d, ]+)\], captionInk: \[([\d, ]+)\] \}/g;
const arr = s => s.split(',').map(Number);
const films = [];
for (const m of src.matchAll(re))
  films.push({ name: m[1], group: m[2], caption: m[3], code: m[4], panel: arr(m[5]), band: arr(m[6]), ink: arr(m[7]), captionInk: arr(m[8]) });
if (films.length !== 20) throw new Error('expected 20 films, found ' + films.length);
writeFileSync(new URL('src/films.gen.mjs', here),
  '// Generated by gen-films.mjs from core/src/filmpack/looks.ts. Do not edit.\nexport const LOOKS = ' + JSON.stringify(films) + ';\n', 'utf8');
console.log('wrote', films.length, 'films');
